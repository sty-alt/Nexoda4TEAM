const russianPrefixes: Array<[string, string]> = [
  ["Invitation sent to ", "Приглашение отправлено: "],
  ["Direct message thread with ", "Личная переписка с "],
  ["Logging in as ", "Входим как "],
  ["Timer started for ", "Таймер запущен для "],
  ["Timer started: ", "Таймер запущен: "],
  ["Task created: ", "Задача создана: "],
  ["Created: ", "Создано: "],
  ["Channel #", "Канал #"],
  ["Connected repository ", "Подключён репозиторий "],
];

function normalize(source: string) {
  return source.replace(/\s+/g, " ").trim();
}

export function translate(locale: Locale, source: string): string {
  if (locale === "en") return source;
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  const key = normalize(source);
  if (locale === "ru") {
    const prefix = russianPrefixes.find(([candidate]) => source.startsWith(candidate));
    if (prefix) return `${prefix[1]}${source.slice(prefix[0].length)}`;
    const updatedTasks = source.match(/^Updated (\d+) tasks to (.+)$/);
    if (updatedTasks) return `Обновлено задач: ${updatedTasks[1]}, статус: ${translate(locale, updatedTasks[2])}`;
    const deletedTasks = source.match(/^Deleted (\d+) tasks$/);
    if (deletedTasks) return `Удалено задач: ${deletedTasks[1]}`;
  }
  const translated = russian.get(key);
  return translated ? `${leading}${translated}${trailing}` : source;
}

